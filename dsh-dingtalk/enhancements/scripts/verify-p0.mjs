import assert from 'node:assert/strict';
import { mkdir, readFile, lstat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fixture } from './p0-fixture.mjs';
import { dingtalkTool } from '../lib/host/tool.js';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { Context } from '@deepseek-ai/cordis';
const f = await fixture({ automatic: true }); const checks = [];
const native = new Context();
try {
  const fromDsh = createRequire(resolve('../.cache/dingtalk-g0/dsh-runtime/package.json'));
  const { SystemPrompt } = await import(pathToFileURL(fromDsh.resolve('@deepseek-ai/dsh-system-prompt')).href);
  const { ToolRuntime } = await import(pathToFileURL(fromDsh.resolve('@deepseek-ai/dsh-tools')).href);
  await native.plugin(SystemPrompt, {}); await native.plugin(ToolRuntime, { mode: 'native' });
  const registered = await native.plugin({ inject: ['tools'], apply(ctx) { ctx.tools.register(dingtalkTool(f.service)); } });
  const nativeResult = await native.get('tools').execute({ name: 'dingtalk_call', callId: 'synthetic-call', arguments: { operationId: 'identity.getSelf', args: {} }, signal: new AbortController().signal });
  assert.equal(nativeResult.isError, false); assert.equal(nativeResult.value.status, 'auth_required');
  assert.deepEqual(JSON.parse(nativeResult.content[0].text), nativeResult.value);
  await registered.dispose();
  const removed = await native.get('tools').execute({ name: 'dingtalk_call', callId: 'removed-call', arguments: { operationId: 'identity.getSelf', args: {} }, signal: new AbortController().signal });
  assert.equal(removed.isError, true);
  checks.push('official DSH ToolRuntime registers, executes and renders canonical auth_required; unload removes Tool');
  const tool = dingtalkTool(f.service), signal = new AbortController().signal;
  assert.equal((await tool.execute({ operationId: 'identity.getSelf', args: {} }, { signal })).status, 'auth_required');
  await assert.rejects(f.service.beginAuthorization({}), { reasonCode: 'invalid_request' });
  await assert.rejects(f.service.disconnect(), { reasonCode: 'invalid_request' });
  checks.push('unbound Tool cannot read default credentials or invoke UI authorization/revocation');
  const before = await f.defaultAccount();
  assert.equal(before.currentProfile, 'test-corp:other-user');
  const connected = await f.authorize();
  assert.equal(connected.state, 'connected', connected.reasonCode);
  assert.ok(connected.checkedAt); assert.ok(!JSON.stringify(connected).includes('test-user'));
  assert.equal(f.events.filter(e => e.type === 'install').length, 1);
  assert.equal(f.events.filter(e => e.type === 'discover').length, 1);
  checks.push('no JSON, app credentials or expected identity: first Connect installs pinned DWS and discovers app; online identity creates binding');
  checks.push('loopback state+cookie callback -> official stdin exchange -> online exact identity -> connected');
  for (const args of [{ operationId: 'identity.getSelf', args: {} }, { operationId: 'calendar.listEvents', args: { limit: 2 } }, { operationId: 'docs.search', args: { query: 'privacy-sentinel-query', limit: 2 } }]) assert.equal((await tool.execute(args, { signal })).status, 'ok');
  for (const args of [{ operationId: 'docs.delete', args: {} }, { operationId: 'docs.search', args: { profile: 'other' } }, { operationId: 'auth.logout', args: {} }]) assert.equal((await tool.execute(args, { signal })).reasonCode, 'invalid_request');
  checks.push('all three read-only Tool operations succeed; writes, arbitrary Profile and auth Tool requests rejected');
  f.state.businessFailure = true;
  const denied = await tool.execute({ operationId: 'docs.search', args: { query: 'privacy-sentinel-error-query' } }, { signal });
  assert.equal(denied.status, 'failed'); assert.notEqual(denied.reasonCode, 'org_cli_disabled');
  f.state.businessFailure = false;
  const plain = await f.allPlaintext();
  for (const value of ['privacy-sentinel-query', 'privacy-sentinel-error-query', 'private-response-body', 'synthetic-test-user-access', 'synthetic-test-user-refresh', 'synthetic-code']) assert.ok(!plain.includes(value), `Synthetic private material persisted: ${value}`);
  assert.ok((await lstat(join(f.config, 'logs'))).isFile());
  checks.push('official DWS success/error paths create no diagnostic log or plaintext query/code/Token');
  await f.restart(); assert.equal((await f.service.status()).state, 'connected');
  f.state.cancel = true; assert.equal((await f.authorize()).state, 'user_cancelled'); f.state.cancel = false;
  assert.equal((await f.service.status()).state, 'connected');
  f.state.exchangeFailure = true; assert.notEqual((await f.authorize()).state, 'connected'); f.state.exchangeFailure = false;
  assert.equal((await f.service.status()).state, 'connected');
  checks.push('restart re-verifies binding; cancelled and pre-save failed reauthorization preserve existing working binding');
  f.state.user = 'wrong-user';
  assert.notEqual((await f.authorize()).state, 'connected'); f.state.user = 'test-user';
  assert.equal((await f.service.status()).state, 'connected');
  checks.push('official pre-save wrong-account rejection leaves the existing expected binding usable');
  f.state.failIdentityAt = f.state.identityCalls + 2;
  assert.equal((await f.authorize()).reasonCode, 'verification_failed_after_save'); f.state.failIdentityAt = -1;
  assert.equal((await f.service.status()).reasonCode, 'verification_failed_after_save');
  assert.equal((await f.service.invoke({ operationId: 'identity.getSelf', args: {} })).status, 'auth_required');
  assert.equal((await f.authorize()).state, 'connected');
  checks.push('post-save verification failure blocks reads rather than claiming rollback/success; explicit reauthorization recovers');
  await f.managed.ui('test-browser', f.context, () => f.service.disconnect());
  assert.equal((await f.service.status()).state, 'unlinked');
  assert.equal((await f.service.invoke({ operationId: 'identity.getSelf', args: {} })).status, 'auth_required');
  const after = JSON.parse(await readFile(join(f.config, 'profiles.json'), 'utf8'));
  assert.equal(after.currentProfile, before.currentProfile);
  assert.deepEqual(after.profiles.find(p => p.userId === 'other-user'), before.profiles.find(p => p.userId === 'other-user'));
  checks.push('exact Profile logout blocks later reads and leaves other Profile/default unchanged');
  await f.restart(); assert.equal((await f.service.status()).state, 'unlinked');
  await writeFile(join(f.config, 'logs'), 'tamper');
  assert.equal((await f.service.status()).reasonCode, 'privacy_guard_required');
  checks.push('revoked binding survives restart; tampered privacy guard fails closed');
  assert.deepEqual(f.failures, []);
  const report = { success: true, classification: 'OFFICIAL_BINARY_SYNTHETIC_ENDPOINTS_ONLY', checks, realAuthorization: false, realBusinessData: false, g1: 'BLOCKED', limitations: ['Enterprise enabled/disabled account test pending', 'Real LLM intent selection pending', 'Desktop shell acceptance pending', 'Post-save verification failure cannot restore previous DWS credentials'] };
  await mkdir('artifacts', { recursive: true }); await writeFile('artifacts/p0-local-report.json', JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
} finally { await native.fiber.dispose(); await f.dispose(); }
